"""Build, test and install build-loop's native hook binary (``bin/native/bl``).

Freshness contract
------------------
``bl`` mirrors Python and shell in this repo. One SHA-256 digest covers every
file whose change can change what ``bl`` should do: ``crates/**``,
``Cargo.toml``, ``Cargo.lock`` and the mirrored sources in ``MIRRORED``.
No digest is stored in git, so no git path (commit, merge, rebase) has to
keep one current.

- ``bin/native/bl.sources`` (ignored) holds the digest the installed binary was
  built from. It is written last, only after every test passed.
- ``bin/native/sources.current`` (ignored) holds the digest of the tree as it
  is now. SessionStart rewrites it in the background, and the PostToolUse
  Edit|Write hook (``hooks/pre-edit-architecture.sh``), in a session whose
  project directory is this checkout, first overwrites it
  with a ``stale <pid>`` marker, then recomputes it in the background, so an
  agent edit turns the binary off at once. ``--write-current`` skips its write
  when another writer changed the file while it hashed (compare, then replace).
- ``hooks/pre-edit-rally-point.sh``, the tool-trace commands in
  ``hooks/hooks.json`` (generated by ``scripts/trace_hook_command.py``), the
  SessionStart commands (``scripts/session_start_hook_command.py``),
  ``scripts/hooks/pre_bash_dispatch.sh`` and ``scripts/hooks/stop_finalize.sh``
  run the binary only when the first lines of the two files are equal, read
  with shell builtins. A missing, empty or different file runs the shell or
  Python hook.

The digest hashes working-tree bytes of the files ``git ls-files`` lists under
those paths (the build compiles working-tree bytes). Paths are repo-relative
and sorted; no mtimes, modes or absolute paths enter it. Without git (an
installed plugin copy) no digest can be computed, nothing is written, and the
binary stays off.

Known gap: a source change made outside an agent Edit/Write in a session
whose project is this checkout (git checkout, pull or merge run through Bash,
an external editor, an edit from another project) is picked up only at the
next SessionStart or agent edit here. The SessionStart hook itself compares against
the previous value, because the refresh runs beside it, not before it.

Usage
-----
``python3 scripts/build_native.py``            build, test, install (exit 0 on install)
``python3 scripts/build_native.py --check``    is the installed binary fresh?
``python3 scripts/build_native.py --write-current``  rewrite bin/native/sources.current
``--dest DIR`` installs (or checks, or writes) in ``DIR`` instead of ``bin/native``.

The build runs ``cargo build --release --locked``, ``cargo test --locked`` and
the parity harness (``tests/hook_parity``: pre-edit, tool-trace and session-start cases)
against ``target/release/bl``, then
installs. Installing into the repo's own ``bin/native`` also reruns the
launcher parity cases through the real hook script; if they fail the sidecar
is removed, so the launcher goes back to the shell hook.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SIDECAR_NAME = "bl.sources"
CURRENT_NAME = "sources.current"
DEFAULT_DEST = REPO / "bin" / "native"

# Python and shell whose behaviour crates/bl and crates/bl-contract reproduce
# (their doc comments cite these modules), plus the modules hooks.py loads on
# the mirrored pre-edit path.
MIRRORED = (
    "hooks/_bounded_hook.sh",
    "hooks/pre-edit-rally-point.sh",
    "scripts/hook_payload.py",
    "scripts/rally_point/actor_identity.py",
    "scripts/rally_point/backend_adapter.py",
    "scripts/rally_point/channel_paths.py",
    "scripts/rally_point/discovery_bridge.py",
    "scripts/rally_point/hook_budget.py",
    "scripts/rally_point/hooks.py",
    # bl hook trace: tool_trace.py and the modules its hook path imports
    # (lock primitive, bounded state.json reader, run identity).
    "scripts/atomic_io.py",
    "scripts/rally_point/build_loop_id.py",
    "scripts/temporal_membership.py",
    "scripts/tool_trace.py",
    "scripts/transcript_adapter.py",
    # bl hook session-start: the five shell hooks it stands in for, their
    # helpers, and the merge rule and registration it shares with Python.
    "hooks/_resolve_python.sh",
    "hooks/_session_start_lib.sh",
    "hooks/closeout.sh",
    "hooks/session-start-architecture.sh",
    "hooks/session-start-codex-hook-trust.sh",
    "hooks/session-start-rally-point.sh",
    "hooks/session-start-tool-state.sh",
    "scripts/session_start_hook_command.py",
    "scripts/tool_state_paths.py",
    "scripts/codex_hook_trust_check.py",
    "scripts/hooks/pre_bash_dispatch.sh",
    "scripts/hooks/stop_finalize.sh",
)
# Every path whose change changes the digest.
WATCHED = ("Cargo.toml", "Cargo.lock", "crates/") + MIRRORED

class BuildError(Exception):
    """A step failed; the message is the one-line reason."""


def source_paths(repo: Path = REPO) -> list[str]:
    """Sorted repo-relative paths the digest covers."""
    cp = subprocess.run(
        ["git", "-C", str(repo), "ls-files", "-z", "--", *WATCHED],
        capture_output=True,
    )
    if cp.returncode != 0:
        raise BuildError("git ls-files failed: " + cp.stderr.decode(errors="replace").strip())
    paths = sorted({p for p in cp.stdout.decode().split("\0") if p})
    missing = [m for m in MIRRORED if m not in paths]
    if missing:
        raise BuildError("mirrored file not tracked: " + ", ".join(missing))
    return paths


def compute_digest(repo: Path = REPO) -> str:
    """Digest of the watched sources' working-tree bytes."""
    h = hashlib.sha256(b"build-loop native sources v1\n")
    for rel in source_paths(repo):
        try:
            data = (repo / rel).read_bytes()
        except OSError:
            raise BuildError(f"cannot read {rel}") from None
        h.update(rel.encode() + b"\0" + hashlib.sha256(data).hexdigest().encode() + b"\n")
    return h.hexdigest()


def read_first_line(path: Path) -> str:
    """First line of ``path`` (``""`` when absent or unreadable)."""
    try:
        return path.read_text(encoding="utf-8").split("\n", 1)[0].strip()
    except (OSError, UnicodeDecodeError):
        return ""


def _read_raw(path: Path) -> bytes | None:
    try:
        return path.read_bytes()
    except OSError:
        return None


def write_current(repo: Path = REPO, dest: Path = DEFAULT_DEST) -> str | None:
    """Rewrite ``dest/sources.current`` with the tree's digest.

    Returns the digest, or None when nothing was written: the digest could not
    be computed (no git, a mirrored file missing), or another writer changed
    the file while this one hashed. That writer started later, so its value
    (a ``stale`` marker or a newer digest) must win.
    """
    path = dest / CURRENT_NAME
    before = _read_raw(path)
    try:
        digest = compute_digest(repo)
    except BuildError:
        return None
    if _read_raw(path) != before:
        return None
    dest.mkdir(parents=True, exist_ok=True)
    tmp = dest / f"{CURRENT_NAME}.{os.getpid()}.tmp"
    tmp.write_text(digest + "\n", encoding="utf-8")
    os.replace(tmp, path)
    return digest


def run_step(label: str, argv: list[str], repo: Path, env: dict[str, str] | None = None) -> None:
    """Run one build step in ``repo``; raise BuildError naming it on failure."""
    print(f"build_native: {label}", file=sys.stderr, flush=True)
    cp = subprocess.run(argv, cwd=str(repo), env={**os.environ, **(env or {})})
    if cp.returncode != 0:
        raise BuildError(f"{label} failed (exit {cp.returncode})")


def install(built: Path, dest: Path, digest: str) -> None:
    """Replace ``dest/bl`` and then write its sidecar, each atomically.

    The old sidecar goes first, so no moment pairs a new binary with a digest
    it was not built from; an interrupted install leaves the shell hook in use.
    ``sources.current`` gets the same digest last: the build already checked
    that the tree did not change while it ran.
    """
    dest.mkdir(parents=True, exist_ok=True)
    sidecar = dest / SIDECAR_NAME
    sidecar.unlink(missing_ok=True)
    tmp = dest / "bl.tmp"
    shutil.copy2(built, tmp)
    tmp.chmod(0o755)
    os.replace(tmp, dest / "bl")
    tmp_sidecar = dest / (SIDECAR_NAME + ".tmp")
    tmp_sidecar.write_text(digest + "\n", encoding="utf-8")
    os.replace(tmp_sidecar, sidecar)
    tmp_current = dest / (CURRENT_NAME + ".tmp")
    tmp_current.write_text(digest + "\n", encoding="utf-8")
    os.replace(tmp_current, dest / CURRENT_NAME)


def dirty_sources(repo: Path = REPO) -> list[str]:
    """Watched tracked files that differ from HEAD or the index."""
    cp = subprocess.run(["git", "-C", str(repo), "status", "--porcelain", "-z",
                         "--untracked-files=no", "--", *WATCHED], capture_output=True)
    if cp.returncode != 0:
        raise BuildError("git status failed")
    paths = [e[3:] for e in cp.stdout.decode().split("\0") if len(e) > 3]
    return sorted(paths)


def build_and_install(repo: Path = REPO, dest: Path = DEFAULT_DEST, run=run_step,
                      allow_dirty: bool = False) -> str:
    if not allow_dirty:
        dirty = dirty_sources(repo)
        if dirty:
            raise BuildError(f"uncommitted changes in {', '.join(dirty)}; commit them "
                             "or pass --allow-dirty (a revert would leave the binary in use)")
    digest = compute_digest(repo)
    # An explicit target dir: CARGO_TARGET_DIR or a cargo config could
    # otherwise build elsewhere and leave an older binary at this path.
    target = repo / "target"
    built = target / "release" / "bl"
    semantic = target / "release" / "examples" / "pre_edit_semantics"
    built.unlink(missing_ok=True)
    semantic.unlink(missing_ok=True)
    run("cargo build", ["cargo", "build", "--release", "--locked", "--bins", "--examples", "--target-dir", str(target)], repo)
    run("cargo test", ["cargo", "test", "--locked", "--target-dir", str(target)], repo)
    if not built.is_file():
        raise BuildError(f"cargo build left no binary at {built}")
    if not semantic.is_file():
        raise BuildError(f"cargo build left no semantic test runner at {semantic}")
    run("parity harness", [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
                           "tests/hook_parity"], repo, {"BL_BIN": str(built), "BL_PRE_EDIT_SEMANTICS_BIN": str(semantic)})
    if compute_digest(repo) != digest:
        raise BuildError("sources changed during the build; run it again")
    install(built, dest, digest)
    if dest.resolve() == (repo / "bin" / "native").resolve():
        try:
            run("launcher parity", [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider",
                                    "tests/hook_parity", "-k", "launcher"], repo)
        except BuildError:
            (dest / SIDECAR_NAME).unlink(missing_ok=True)
            raise
    return digest


def installed_status(repo: Path = REPO, dest: Path = DEFAULT_DEST) -> tuple[bool, str]:
    """(fresh, one-line reason) for the binary installed in ``dest``."""
    if not os.access(dest / "bl", os.X_OK):
        return False, f"no executable {dest / 'bl'}"
    built = read_first_line(dest / SIDECAR_NAME)
    if not built:
        return False, f"{dest / SIDECAR_NAME} missing or empty; the shell hook runs"
    if built != compute_digest(repo):
        return False, "built from other sources than the tree; the shell hook runs"
    if read_first_line(dest / CURRENT_NAME) != built:
        return False, (f"{dest / CURRENT_NAME} missing or stale; the shell hook runs "
                       "until the next refresh writes it")
    return True, f"fresh ({built[:12]})"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write-current", action="store_true",
                      help="rewrite sources.current with the tree's digest (hooks run this)")
    mode.add_argument("--check", action="store_true",
                      help="report whether the installed binary is fresh; no build")
    ap.add_argument("--allow-dirty", action="store_true",
                    help="install even when watched files have uncommitted changes")
    ap.add_argument("--dest", type=Path, default=DEFAULT_DEST,
                    help="native directory (default: bin/native in this repo)")
    args = ap.parse_args(argv)
    try:
        if args.write_current:
            return 0 if write_current(dest=args.dest) else 1
        if args.check:
            fresh, reason = installed_status(dest=args.dest)
            print(f"build_native: {reason}", file=sys.stdout if fresh else sys.stderr)
            return 0 if fresh else 1
        digest = build_and_install(dest=args.dest, allow_dirty=args.allow_dirty)
    except BuildError as exc:
        print(f"build_native: {exc}", file=sys.stderr)
        return 1
    print(f"build_native: installed {args.dest / 'bl'} ({digest[:12]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
